-- Clientes ---------------------------------------------------------------

create table public.clientes (
  -- "by default" permite conservar los ID del Excel al importarlo.
  id bigint generated by default as identity (start with 1001) primary key,
  nombre text not null check (btrim(nombre) <> ''),
  apellidos text not null default '',
  -- Con lada de país y sin espacios, p. ej. 528112345678 (se normaliza solo).
  telefono text not null unique check (telefono ~ '^52[0-9]{10}$'),
  cumple_dia smallint check (cumple_dia between 1 and 31),
  cumple_mes smallint check (cumple_mes between 1 and 12),
  registro timestamptz not null default now(),
  registrado_por uuid references public.perfiles (id),
  notas text not null default '',
  -- Código largo y aleatorio del enlace y QR de la tarjeta digital.
  token_tarjeta uuid not null unique default gen_random_uuid(),
  check ((cumple_dia is null) = (cumple_mes is null))
);

create index clientes_nombre_idx on public.clientes (lower(nombre || ' ' || apellidos));
create index clientes_cumple_idx on public.clientes (cumple_mes, cumple_dia);

-- Compras ----------------------------------------------------------------
-- Cada abono de un apartado se registra igual que una venta, con su ticket.

create table public.compras (
  id bigint generated always as identity primary key,
  cliente_id bigint not null references public.clientes (id),
  fecha timestamptz not null default now(),
  sucursal_id smallint not null references public.sucursales (id),
  total numeric(12, 2) not null check (total > 0),
  ticket text not null check (btrim(ticket) <> ''),
  foto_ticket text, -- ruta del archivo en el bucket "tickets"
  -- Historial estable: se guardan los puntos y el nivel usados al registrarla.
  puntos integer not null default 0,
  nivel_id smallint references public.niveles (id),
  registrada_por uuid not null references public.perfiles (id),
  cancelada boolean not null default false,
  cancelada_por uuid references public.perfiles (id),
  cancelada_en timestamptz,
  motivo_cancelacion text,
  creada_en timestamptz not null default now()
);

-- Folio único por sucursal entre las ventas no canceladas.
create unique index compras_ticket_unico on public.compras (sucursal_id, ticket) where not cancelada;
create index compras_cliente_idx on public.compras (cliente_id, fecha);
create index compras_fecha_idx on public.compras (fecha);
create index compras_empleada_idx on public.compras (registrada_por, fecha);

-- Canjes -----------------------------------------------------------------

create table public.canjes (
  id bigint generated always as identity primary key,
  cliente_id bigint not null references public.clientes (id),
  fecha timestamptz not null default now(),
  sucursal_id smallint not null references public.sucursales (id),
  puntos integer not null check (puntos > 0),
  pesos numeric(12, 2) not null, -- se calcula al guardar con el valor del punto
  registrado_por uuid not null references public.perfiles (id),
  creado_en timestamptz not null default now()
);

create index canjes_cliente_idx on public.canjes (cliente_id, fecha);
create index canjes_fecha_idx on public.canjes (fecha);
