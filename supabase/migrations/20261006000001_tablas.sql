-- Tablas del sistema de ventas y lealtad de Joyería Torres Torres.
-- Diseño: documento "Sistema de ventas y lealtad", sección Datos.
-- Lo calculado (nivel actual, puntos disponibles, vigencia) no se guarda:
-- sale de las compras y canjes (ver 20261006000002_lealtad.sql).

-- Sucursales ------------------------------------------------------------

create table public.sucursales (
  id smallint generated always as identity primary key,
  nombre text not null unique,
  activa boolean not null default true
);

insert into public.sucursales (nombre) values ('Allende'), ('Olmos'), ('Hidalgo');

-- Usuarios (administrador y empleadas) ---------------------------------
-- Las cuentas viven en auth.users (login de Supabase); aquí va su perfil.

create type public.rol as enum ('admin', 'empleada');

create table public.perfiles (
  id uuid primary key references auth.users (id) on delete cascade,
  nombre text not null,
  correo text not null,
  rol public.rol not null default 'empleada',
  activa boolean not null default true,
  creado timestamptz not null default now()
);

-- Reglas del programa de lealtad ---------------------------------------
-- Una sola fila con los parámetros que el administrador puede cambiar.

create table public.configuracion (
  id boolean primary key default true check (id),
  bloque_pesos numeric(10, 2) not null default 10 check (bloque_pesos > 0),
  valor_punto numeric(10, 4) not null default 0.25 check (valor_punto > 0),
  minimo_canje integer not null default 200 check (minimo_canje > 0),
  vigencia_meses integer not null default 6 check (vigencia_meses > 0)
);

insert into public.configuracion default values;

create table public.niveles (
  id smallint generated always as identity primary key,
  nombre text not null unique,
  desde numeric(12, 2) not null unique check (desde >= 0),
  puntos_por_bloque integer not null check (puntos_por_bloque > 0),
  beneficio text not null default ''
);

